#!/usr/bin/env python3
"""Build webui.h from webui.html and hotspot.html.

Both pages are minified first when node (and terser) are available - tools/minify.js -
then gzipped into PROGMEM arrays. Without node the pages are embedded as they are; they
work the same, the gzip is just ~1 KB larger. Run from anywhere; paths are relative to
this script.
"""
import gzip, os, shutil, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def page(name):
    src = open(os.path.join(root, name), 'rb').read()
    if shutil.which('node'):
        try:
            r = subprocess.run(['node', os.path.join(root, 'tools', 'minify.js'), os.path.join(root, name)], capture_output=True, timeout=60)
            if r.returncode == 0 and r.stdout:
                return src, r.stdout
            sys.stderr.write('minify failed for %s, embedding unminified\n%s\n' % (name, r.stderr.decode()[:300]))
        except Exception as e:
            sys.stderr.write('minify skipped for %s: %s\n' % (name, e))
    return src, src

def array(ident, comment, raw, mini):
    gz = gzip.compress(mini, compresslevel=9, mtime=0)
    lines = ['  ' + ','.join('0x%02x' % b for b in gz[i:i + 20]) + ',' for i in range(0, len(gz), 20)]
    text = ('// %s: %d bytes source, %d minified, %d gzipped.\n'
            'static const uint8_t %s[] PROGMEM = {\n%s\n};\nstatic const size_t %s_LEN = %d;\n') % (
        comment, len(raw), len(mini), len(gz), ident, '\n'.join(lines), ident, len(gz))
    return text, len(gz)

out = '#pragma once\n#include <Arduino.h>\n// Generated by tools/make_webui.py - do not edit. Edit webui.html / hotspot.html instead.\n\n'
a, n1 = array('INDEX_HTML_GZ', 'Console page (webui.html)', *page('webui.html'))
b, n2 = array('HOTSPOT_HTML_GZ', 'Fallback hotspot page (hotspot.html)', *page('hotspot.html'))
open(os.path.join(root, 'webui.h'), 'w').write(out + a + '\n' + b)
print('webui.h: console %d bytes gz, hotspot %d bytes gz' % (n1, n2))
